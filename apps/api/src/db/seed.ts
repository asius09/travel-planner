async function seed() {
  console.log('Seeding destinations...')
  
  for (const dest of seedDestinations) {
    const existing = await db.query.destinations.findFirst({
      where: eq(destinations.slug, dest.slug),
    })
    
    if (!existing) {
      await db.insert(destinations).values(dest)
      console.log(`Inserted: ${dest.name}`)
    } else {
      console.log(`Skipped (exists): ${dest.name}`)
    }
  }
  
  console.log('Seeding complete!')
  process.exit(0)
}

seed().catch((error) => {
  console.error('Seed failed:', error)
  process.exit(1)
})